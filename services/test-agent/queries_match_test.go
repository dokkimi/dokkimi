package main

import "testing"

func TestQueriesMatch(t *testing.T) {
	cases := []struct {
		name         string
		logged, step string
		want         bool
	}{
		{"same text", "SELECT 1", "SELECT 1", true},
		{"different text", "SELECT 1", "SELECT 2", false},
		{"key order", `{"a":1,"b":2}`, `{"b":2,"a":1}`, true},
		{"filter by _id",
			`{"operation":"findOne","collection":"c","filter":{"_id":5}}`,
			`{"operation":"findOne","collection":"c","filter":{"_id":5}}`, true},
		{"filter by a different _id",
			`{"operation":"findOne","collection":"c","filter":{"_id":6}}`,
			`{"operation":"findOne","collection":"c","filter":{"_id":5}}`, false},
		{"insertOne: _id generated by the driver",
			`{"operation":"insertOne","collection":"c","document":{"_id":"65f0c0ffee0000000000abcd","v":1}}`,
			`{"operation":"insertOne","collection":"c","document":{"v":1}}`, true},
		{"insertOne: _id given by the step must match",
			`{"operation":"insertOne","collection":"c","document":{"_id":2,"v":1}}`,
			`{"operation":"insertOne","collection":"c","document":{"_id":1,"v":1}}`, false},
		{"insertMany: generated _ids",
			`{"operation":"insertMany","collection":"c","documents":[{"_id":"a1","v":1},{"_id":7,"v":2}]}`,
			`{"operation":"insertMany","collection":"c","documents":[{"v":1},{"_id":7,"v":2}]}`, true},
		{"find: an _id only in the log is not ignored",
			`{"operation":"find","collection":"c","filter":{"_id":5}}`,
			`{"operation":"find","collection":"c","filter":{}}`, false},
	}
	for _, c := range cases {
		if got := queriesMatch(c.logged, c.step); got != c.want {
			t.Errorf("%s: got %v, want %v", c.name, got, c.want)
		}
	}
}
